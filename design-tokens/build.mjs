#!/usr/bin/env node
/**
 * ShopStack 设计令牌生成器
 * ------------------------------------------------------------
 * 单一数据源: design-tokens/tokens.json
 *
 * 生成产物:
 *   design-tokens/generated/tokens.css    -> Vue3 / React (CSS 变量)
 *   design-tokens/generated/tokens.scss   -> Vue3 (SCSS 变量 + CSS 变量)
 *   design-tokens/generated/tokens.ts     -> React / Vue3 (类型化常量)
 *   design-tokens/generated/tokens.dart   -> Flutter
 *   design-tokens/generated/tokens.wxss   -> 微信小程序
 *   design-tokens/generated/tokens.json   -> 小程序/原生可直接 import
 *
 * 用法: node design-tokens/build.mjs
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(__dirname, 'generated');
const tokens = JSON.parse(readFileSync(join(__dirname, 'tokens.json'), 'utf8'));

mkdirSync(OUT_DIR, { recursive: true });

const banner = `/* Auto-generated by design-tokens/build.mjs. DO NOT EDIT.
 * Source: design-tokens/tokens.json (ShopStack Design System v${tokens.version})
 */`;

/** 元数据字段，不参与令牌产物 */
const META_KEYS = new Set(['$schema', 'name', 'version', 'description', 'meta']);

/** 把 token 对象拍平成 { 'brand-500': '#3B63F6' } 形式 */
function flatten(obj, prefix = '', isRoot = true) {
  const out = {};
  for (const [key, value] of Object.entries(obj)) {
    if (isRoot && META_KEYS.has(key)) continue;
    const name = prefix ? `${prefix}-${key}` : key;
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      Object.assign(out, flatten(value, name, false));
    } else {
      out[name] = value;
    }
  }
  return out;
}

const flat = flatten(tokens);

// ---------------------------------------------------------------- CSS
const cssVars = Object.entries(flat)
  .map(([k, v]) => `  --ss-${kebab(k)}: ${v};`)
  .join('\n');

writeFileSync(
  join(OUT_DIR, 'tokens.css'),
  `${banner}\n:root {\n${cssVars}\n}\n`
);

writeFileSync(
  join(OUT_DIR, 'tokens.scss'),
  `${banner}\n` +
    Object.entries(flat)
      .map(([k, v]) => `$ss-${kebab(k)}: ${v};`)
      .join('\n') +
    '\n'
);

function kebab(s) {
  return s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

// ---------------------------------------------------------------- TS
const tsEntries = Object.entries(flat)
  .map(([k, v]) => `  '${kebab(k)}': ${JSON.stringify(v)},`)
  .join('\n');

writeFileSync(
  join(OUT_DIR, 'tokens.ts'),
  `${banner}\n\n` +
    `export const tokens = {\n${tsEntries}\n} as const;\n\n` +
    `export type TokenKey = keyof typeof tokens;\n\n` +
    `export function token<K extends TokenKey>(key: K): (typeof tokens)[K] {\n` +
    `  return tokens[key];\n}\n\n` +
    `export const breakpoints = {\n` +
    Object.entries(tokens.breakpoint)
      .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`)
      .join('\n') +
    `\n} as const;\n`
);

// ---------------------------------------------------------------- Dart
const dartEntries = Object.entries(flat)
  .map(([k, v]) => `  static const String ${camel(k)} = ${JSON.stringify(v)};`)
  .join('\n');

writeFileSync(
  join(OUT_DIR, 'tokens.dart'),
  `${banner}\n\n` +
    `class AppColors {\n  AppColors._();\n\n${dartEntries}\n}\n\n` +
    `class AppBreakpoints {\n  AppBreakpoints._();\n\n` +
    Object.entries(tokens.breakpoint)
      .map(([k, v]) => `  static const double ${camel(k)} = ${parseFloat(v)};`)
      .join('\n') +
    `\n}\n`
);

function camel(s) {
  return s.replace(/[-_]([a-z0-9])/g, (_, c) => c.toUpperCase());
}

// ---------------------------------------------------------------- WXSS
const wxssVars = Object.entries(flat)
  .map(([k, v]) => `  --ss-${kebab(k)}: ${v};`)
  .join('\n');

writeFileSync(
  join(OUT_DIR, 'tokens.wxss'),
  `${banner}\npage {\n${wxssVars}\n}\n`
);

// ---------------------------------------------------------------- JSON (小程序可直接引用)
writeFileSync(
  join(OUT_DIR, 'tokens.json'),
  `${JSON.stringify(tokens, null, 2)}\n`
);

console.log(`✔ design tokens generated -> ${OUT_DIR}`);
console.log(`  ${Object.keys(flat).length} tokens -> tokens.css / tokens.ts / tokens.dart / tokens.wxss`);
